import time

def evaluate(model, loader):
    model.eval()
    crit = nn.CrossEntropyLoss()
    loss_sum, correct, n = 0, 0, 0
    preds, labels = [], []
    with torch.no_grad():
        for x, y in loader:
            x, y = x.to(device), y.to(device)
            with torch.autocast(device_type="cuda", enabled=(device == "cuda")):
                out = model(x)
            loss_sum += crit(out, y).item() * len(y)
            p = out.argmax(1)
            correct += (p == y).sum().item()
            n += len(y)
            preds += p.cpu().tolist()
            labels += y.cpu().tolist()
    return loss_sum / n, correct / n, np.array(preds), np.array(labels)

def fit(model, train_loader, val_loader, epochs, lr):
    params = [p for p in model.parameters() if p.requires_grad]
    opt = torch.optim.AdamW(params, lr=lr, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=lr, total_steps=epochs * len(train_loader))
    scaler = torch.amp.GradScaler(enabled=(device == "cuda"))
    crit = nn.CrossEntropyLoss()
    for ep in range(epochs):
        model.train()
        t0, run = time.time(), 0
        for x, y in train_loader:
            x, y = x.to(device), y.to(device)
            opt.zero_grad()
            with torch.autocast(device_type="cuda", enabled=(device == "cuda")):
                loss = crit(model(x), y)
            scaler.scale(loss).backward()
            scaler.step(opt)
            scaler.update()
            sched.step()
            run += loss.item() * len(y)
        vl, va, _, _ = evaluate(model, val_loader)
        print(f"epoch {ep+1}/{epochs} | train_loss {run/len(train_loader.dataset):.4f} | val_loss {vl:.4f} | val_acc {va:.4f} | {time.time()-t0:.0f} san")

fit(model, train_loader, val_loader, epochs=3, lr=1e-3)

